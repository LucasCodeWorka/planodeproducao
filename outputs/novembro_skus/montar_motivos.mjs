import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const data = JSON.parse(await fs.readFile('outputs/novembro_skus/preparado.json', 'utf8'));
const motivos = JSON.parse(await fs.readFile('outputs/novembro_skus/motivos.json', 'utf8'));
const linhas = data.rows.map((linha) => [...linha, motivos[String(linha[2])] || '']);
const wb = Workbook.create();
const sheet = wb.worksheets.add('Pedidos');
const lastRow = linhas.length + 1;
sheet.showGridLines = false;
sheet.getRange(`A1:Z${lastRow}`).values = [[...data.headers, 'Motivo fora da matriz'], ...linhas];
sheet.getRange('A1:Z1').format = { fill: '#274862', font: { name: 'Arial', bold: true, color: '#FFFFFF', size: 10 }, wrapText: true, verticalAlignment: 'center', rowHeight: 43 };
sheet.getRange(`A2:Z${lastRow}`).format.font = { name: 'Arial', size: 10 };
sheet.getRange('A:A').format.columnWidth = 13;
sheet.getRange('B:B').format.columnWidth = 9;
sheet.getRange('C:D').format.columnWidth = 14;
sheet.getRange('E:E').format.columnWidth = 46;
sheet.getRange('F:H').format.columnWidth = 17;
sheet.getRange('I:K').format.columnWidth = 17;
sheet.getRange('L:V').format.columnWidth = 20;
sheet.getRange('W:W').format.columnWidth = 28;
sheet.getRange('X:X').format.columnWidth = 21;
sheet.getRange('Y:Y').format.columnWidth = 28;
sheet.getRange('Z:Z').format.columnWidth = 75;
sheet.getRange(`Z2:Z${lastRow}`).format.wrapText = true;
sheet.getRange(`A2:Z${lastRow}`).format.rowHeight = 42;
sheet.getRange(`I2:V${lastRow}`).setNumberFormat('#,##0.00;[Red]-#,##0.00');
sheet.freezePanes.freezeRows(1);
const tabela = sheet.tables.add(`A1:Z${lastRow}`, true, 'PedidosNovembro');
tabela.showFilterButton = true;
wb.recalculate();
const check = await wb.inspect({ kind: 'table', range: 'Pedidos!W1:Z5', include: 'values', tableMaxRows: 5, tableMaxCols: 4, maxChars: 4000 });
console.log(check.ndjson);
const preview = await wb.render({ sheetName: 'Pedidos', range: 'W1:Z8', scale: 1, format: 'png' });
await fs.writeFile('outputs/novembro_skus/preview_motivos.png', new Uint8Array(await preview.arrayBuffer()));
const xlsx = await SpreadsheetFile.exportXlsx(wb);
await xlsx.save('outputs/novembro_skus/Pedidos_cobertura_novembro_com_motivo.xlsx');
console.log(`Gerado: ${linhas.length} linhas, ${Object.keys(motivos).length} SKUs fora da matriz.`);
