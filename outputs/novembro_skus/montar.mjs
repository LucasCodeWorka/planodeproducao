import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const data = JSON.parse(await fs.readFile('outputs/novembro_skus/preparado.json', 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('Pedidos');
const lastRow = data.rows.length + 1;
sheet.showGridLines = false;
sheet.getRange(`A1:Y${lastRow}`).values = [data.headers, ...data.rows];
sheet.getRange('A1:Y1').format = { fill: '#274862', font: { name: 'Arial', bold: true, color: '#FFFFFF', size: 10 }, wrapText: true, verticalAlignment: 'center', rowHeight: 43 };
sheet.getRange(`A2:Y${lastRow}`).format.font = { name: 'Arial', size: 10 };
sheet.getRange('A:A').format.columnWidth = 13;
sheet.getRange('B:B').format.columnWidth = 9;
sheet.getRange('C:D').format.columnWidth = 14;
sheet.getRange('E:E').format.columnWidth = 46;
sheet.getRange('F:H').format.columnWidth = 17;
sheet.getRange('I:K').format.columnWidth = 17;
sheet.getRange('L:V').format.columnWidth = 20;
sheet.getRange('W:W').format.columnWidth = 28;
sheet.getRange('X:X').format.columnWidth = 21;
sheet.getRange('Y:Y').format.columnWidth = 28;
sheet.getRange(`I2:V${lastRow}`).setNumberFormat('#,##0.00;[Red]-#,##0.00');
sheet.freezePanes.freezeRows(1);
const tabela = sheet.tables.add(`A1:Y${lastRow}`, true, 'PedidosNovembro');
tabela.showFilterButton = true;
wb.recalculate();
const resumo = await wb.inspect({ kind: 'table', range: 'Pedidos!L1:Y5', include: 'values', tableMaxRows: 5, tableMaxCols: 14, maxChars: 4000 });
console.log(resumo.ndjson);
const preview = await wb.render({ sheetName: 'Pedidos', range: 'L1:Y8', scale: 1, format: 'png' });
await fs.writeFile('outputs/novembro_skus/preview.png', new Uint8Array(await preview.arrayBuffer()));
const arquivo = await SpreadsheetFile.exportXlsx(wb);
await arquivo.save('outputs/novembro_skus/Pedidos_cobertura_novembro_2026.xlsx');
console.log(`Arquivo gerado com ${data.rows.length} linhas.`);
